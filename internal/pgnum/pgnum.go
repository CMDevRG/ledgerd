// Package pgnum maps PostgreSQL NUMERIC values to Go's math/big.Int.
//
// Ledger amounts and balances are whole numbers stored as NUMERIC(38,0). The
// pgx driver represents NUMERIC as a mantissa and a decimal exponent
// (value = Int × 10^Exp) and, depending on the wire format and the digits
// involved, may return the same number as {Int: 1, Exp: 21} or as
// {Int: 1000000000000000000000, Exp: 0}. Int hides that: it always yields the
// exact integer, and refuses anything that is not a finite whole number.
//
// Int implements pgtype.NumericValuer and pgtype.NumericScanner, so pgx (and
// code generated by sqlc) can bind and read it directly, with no conversion
// through strings or floating point.
package pgnum

import (
	"errors"
	"fmt"
	"math/big"

	"github.com/jackc/pgx/v5/pgtype"
)

// maxExponent bounds the decimal exponent accepted from the database. A
// NUMERIC(38,0) never needs more than a few dozen; the cap protects against
// allocating a huge number from a malformed value.
const maxExponent = 1000

// Int is a non-NULL integer stored in a NUMERIC column.
type Int struct {
	V *big.Int
}

// FromBig wraps a copy of v.
func FromBig(v *big.Int) Int {
	if v == nil {
		return Int{}
	}
	return Int{V: new(big.Int).Set(v)}
}

// Big returns a copy of the value (0 for the zero Int).
func (i Int) Big() *big.Int {
	if i.V == nil {
		return new(big.Int)
	}
	return new(big.Int).Set(i.V)
}

// NumericValue implements pgtype.NumericValuer.
func (i Int) NumericValue() (pgtype.Numeric, error) {
	if i.V == nil {
		return pgtype.Numeric{}, errors.New("pgnum: cannot encode a nil integer")
	}
	return pgtype.Numeric{Int: new(big.Int).Set(i.V), Exp: 0, Valid: true}, nil
}

// ScanNumeric implements pgtype.NumericScanner.
func (i *Int) ScanNumeric(n pgtype.Numeric) error {
	v, err := toBig(n)
	if err != nil {
		return err
	}
	i.V = v
	return nil
}

func toBig(n pgtype.Numeric) (*big.Int, error) {
	switch {
	case !n.Valid:
		return nil, errors.New("pgnum: unexpected NULL")
	case n.NaN:
		return nil, errors.New("pgnum: unexpected NaN")
	case n.InfinityModifier != pgtype.Finite:
		return nil, errors.New("pgnum: unexpected infinity")
	case n.Int == nil:
		return nil, errors.New("pgnum: numeric without a mantissa")
	case n.Exp > maxExponent || n.Exp < -maxExponent:
		return nil, fmt.Errorf("pgnum: exponent %d out of range", n.Exp)
	}

	v := new(big.Int).Set(n.Int)
	switch {
	case n.Exp > 0:
		pow := new(big.Int).Exp(big.NewInt(10), big.NewInt(int64(n.Exp)), nil)
		v.Mul(v, pow)
	case n.Exp < 0:
		pow := new(big.Int).Exp(big.NewInt(10), big.NewInt(int64(-n.Exp)), nil)
		q, r := new(big.Int).QuoRem(v, pow, new(big.Int))
		if r.Sign() != 0 {
			return nil, errors.New("pgnum: value has a fractional part")
		}
		v = q
	}
	return v, nil
}
